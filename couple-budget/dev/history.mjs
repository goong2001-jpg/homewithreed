// 이 앱의 git 이력을 읽고 CHANGELOG.md 항목을 만드는 공용 함수들.
// changelog.mjs(배포 후 이력 기록)와 version-json.mjs(배포 버전 표시)가 같이 쓴다.
// 외부 패키지 없이 Node 18+ 만으로 돈다 (Actions 에서 npm ci 없이 바로 실행하려고).

import { execFileSync } from 'node:child_process';

export const APP_DIR = 'couple-budget';
export const START = '<!-- AUTO-CHANGELOG:START -->';
export const END = '<!-- AUTO-CHANGELOG:END -->';

/** git 명령을 cwd 에서 돌리고 표준출력을 돌려준다 */
export function git(args, cwd) {
  return execFileSync('git', args, { cwd, encoding: 'utf8', maxBuffer: 64 * 1024 * 1024 });
}

/**
 * 이 앱 폴더를 건드린 커밋 해시를 최신순으로.
 *
 * --first-parent: 브랜치에 실제로 "들어온 단위"만 본다. squash 병합이든 병합 커밋이든
 *   PR 하나가 한 줄이 되고, PR 안의 작업 커밋들이 따로따로 기록되지 않는다.
 * CHANGELOG.md 는 빼고 본다 — 자동 기록 커밋이 다시 기록 대상이 되면 끝없이 돈다.
 */
export function appCommits(cwd, { upto = 'HEAD', limit = 50, app = APP_DIR } = {}) {
  const out = git([
    'log', upto, '--first-parent', `-n${limit}`, '--format=%H', '--',
    app, `:(exclude)${app}/CHANGELOG.md`,
  ], cwd);
  return out.split('\n').map(s => s.trim()).filter(Boolean);
}

/** 커밋 하나의 메타데이터 */
export function commitInfo(cwd, sha) {
  const raw = git(['show', '-s', '--format=%H%x00%cI%x00%s%x00%b', sha], cwd);
  const [hash, iso, subject, body = ''] = raw.split('\0');
  return { sha: hash.trim(), iso: iso.trim(), subject: subject.trim(), body };
}

/** 'v16: 무엇을 바꿨는지' → 16. 버전이 없으면 null */
export function parseVersion(title) {
  const m = /(?:^|\s)v(\d+)\s*[:：]/i.exec(title);
  return m ? Number(m[1]) : null;
}

/** 제목 앞의 'v16:' 을 뗀다 (버전은 따로 표시하므로) */
export function stripVersion(title) {
  return title.replace(/^\s*v\d+\s*[:：]\s*/i, '').trim();
}

/** ISO 시각 → '2026-11-12 15:30' (한국 시간) */
export function kst(iso) {
  const d = new Date(iso);
  if (Number.isNaN(d.getTime())) return iso;
  // sv-SE 로캘은 'YYYY-MM-DD HH:mm:ss' 형태를 준다
  return new Intl.DateTimeFormat('sv-SE', {
    timeZone: 'Asia/Seoul', year: 'numeric', month: '2-digit', day: '2-digit',
    hour: '2-digit', minute: '2-digit', hour12: false,
  }).format(d);
}

// 본문에서 버리는 줄: 공동 작성자·세션 링크 같은 꼬리표
const TRAILER = /^(co-authored-by|signed-off-by|claude-session|reviewed-by)\s*:/i;
const NOISE = [
  /^🤖\s*Generated with/i,
  /^https:\/\/claude\.ai\/code\/session_\S+$/i,
  /^-{3,}$/,
  /^_Generated by \[Claude Code\]/i,
];

/**
 * 커밋 본문을 CHANGELOG 에 넣을 모양으로 다듬는다.
 * - 꼬리표(Co-Authored-By 등)와 생성 문구 제거
 * - '## 제목' 은 **굵게** 로 바꾼다 (CHANGELOG 의 항목 구조가 깨지지 않게)
 * - '<!--' 는 무력화한다 (본문이 기록 표시를 흉내 내 중복 검사를 속이지 못하게)
 */
export function cleanBody(body) {
  const lines = String(body ?? '').replace(/\r\n/g, '\n').split('\n')
    .filter(l => !TRAILER.test(l.trim()))
    .filter(l => !NOISE.some(re => re.test(l.trim())))
    .map(l => l.replace(/^\s*#{1,6}\s+(.+)$/, '**$1**'))
    .map(l => l.replace(/<!--/g, '&lt;!--'));
  return lines.join('\n').replace(/\n{3,}/g, '\n\n').trim();
}

/**
 * 커밋 → 화면에 보일 제목·본문.
 * 병합 커밋('Merge pull request #46 from …')은 제목이 쓸모없으므로
 * 본문 첫 줄(= PR 제목)을 제목으로 올린다.
 */
export function describe(info) {
  let title = info.subject;
  let body = cleanBody(info.body);
  if (/^Merge (pull request|branch)\b/i.test(title) && body) {
    const [first, ...rest] = body.split('\n');
    title = first.trim();
    body = [rest.join('\n').trim(), `_(${info.subject})_`].filter(Boolean).join('\n\n');
  }
  return { title, body, version: parseVersion(title) };
}

/** CHANGELOG.md 에 넣을 항목 하나 */
export function buildEntry(info, { repoUrl } = {}) {
  const { title, body, version } = describe(info);
  const short = info.sha.slice(0, 7);
  const hash = repoUrl ? `[\`${short}\`](${repoUrl}/commit/${info.sha})` : `\`${short}\``;
  const head = `### ${version != null ? `v${version}` : '버전 없음'} — ${stripVersion(title)}`;
  return [
    head,
    `\`${kst(info.iso)} KST\` · ${hash}`,
    '',
    ...(body ? [body, ''] : []),
    `<!-- sha:${info.sha} -->`,
    '',
  ].join('\n');
}

/** 이미 기록된 커밋 해시들 (자동·수동 영역 모두) */
export function recordedShas(text) {
  return new Set(Array.from(text.matchAll(/<!-- sha:([0-9a-f]{40}) -->/g), m => m[1]));
}

/**
 * 새 항목들을 자동 영역 맨 위에 넣는다.
 * entries 는 오래된 것부터 — 하나씩 맨 위에 꽂으므로 결과는 최신이 위로 온다.
 */
export function insertEntries(text, entries) {
  const at = text.indexOf(START);
  if (at < 0 || text.indexOf(END) < at) {
    throw new Error(`CHANGELOG.md 에 ${START} / ${END} 표시가 없습니다`);
  }
  let out = text;
  for (const e of entries) {
    const pos = out.indexOf(START) + START.length;
    out = `${out.slice(0, pos)}\n\n${e.trimEnd()}\n${out.slice(pos).replace(/^\n+/, '\n')}`;
  }
  return out;
}

/** 앱 폴더를 건드린 가장 최근 커밋 — 지금 배포된 앱 버전을 말해준다 */
export function latestAppCommit(cwd, opts = {}) {
  const [sha] = appCommits(cwd, { ...opts, limit: 1 });
  return sha ? commitInfo(cwd, sha) : null;
}
